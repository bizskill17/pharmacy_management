/** Idempotent schema, applied automatically when the app connects to the database. */
export const SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  phone VARCHAR(15) NOT NULL UNIQUE,
  email VARCHAR(150),
  password_hash VARCHAR(255) NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('ADMIN','SUPERVISOR','UPLOADER')),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  last_login_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS areas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS parties (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  place VARCHAR(120),
  area_id BIGINT REFERENCES areas(id),
  is_customer BOOLEAN NOT NULL DEFAULT FALSE,
  is_supplier BOOLEAN NOT NULL DEFAULT FALSE,
  source_name VARCHAR(200) UNIQUE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS import_batches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doc_type TEXT NOT NULL CHECK (doc_type IN ('SALE','CF_SALE','PURCHASE')),
  source_kind TEXT NOT NULL CHECK (source_kind IN ('TEMPLATE_UPLOAD','HISTORY')),
  file_name VARCHAR(255) NOT NULL,
  rows_total INTEGER NOT NULL DEFAULT 0,
  rows_created INTEGER NOT NULL DEFAULT 0,
  rows_skipped INTEGER NOT NULL DEFAULT 0,
  rows_failed INTEGER NOT NULL DEFAULT 0,
  error_report JSONB,
  imported_by BIGINT NOT NULL REFERENCES users(id),
  imported_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS documents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doc_type TEXT NOT NULL CHECK (doc_type IN ('SALE','CF_SALE','PURCHASE')),
  doc_no VARCHAR(30) NOT NULL,
  doc_prefix VARCHAR(10) NOT NULL,
  doc_seq INTEGER NOT NULL,
  doc_date DATE NOT NULL,
  financial_year CHAR(7) NOT NULL,
  party_id BIGINT REFERENCES parties(id),
  party_name_raw VARCHAR(200),
  amount NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
  item_count INTEGER,
  receipt_ref VARCHAR(50),
  mr_name VARCHAR(120),
  area_id BIGINT REFERENCES areas(id),
  address VARCHAR(255),
  status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','UPLOADED')),
  remarks TEXT,
  uploaded_by BIGINT REFERENCES users(id),
  legacy_uploaded_by VARCHAR(120),
  uploaded_at TIMESTAMPTZ,
  import_batch_id BIGINT REFERENCES import_batches(id),
  created_by BIGINT REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS attachments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id BIGINT NOT NULL REFERENCES documents(id),
  kind TEXT NOT NULL CHECK (kind IN ('RECEIPT_COPY','INVOICE_PHOTO','CHALLAN_PHOTO','GOODS_PHOTO')),
  file_key VARCHAR(500) NOT NULL,
  original_name VARCHAR(255),
  mime_type VARCHAR(100) NOT NULL,
  size_bytes BIGINT NOT NULL,
  sort_order SMALLINT NOT NULL,
  legacy_path VARCHAR(500),
  uploaded_by BIGINT REFERENCES users(id),
  uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES users(id),
  action TEXT NOT NULL,
  entity_type TEXT NOT NULL,
  entity_id BIGINT,
  before_data JSONB,
  after_data JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS documents_unique_active
  ON documents (doc_type, doc_no, financial_year) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS documents_pending ON documents (doc_type, status, doc_date);
CREATE INDEX IF NOT EXISTS documents_series ON documents (doc_type, doc_prefix, financial_year, doc_seq);
CREATE INDEX IF NOT EXISTS documents_party ON documents (party_id, doc_date);
CREATE INDEX IF NOT EXISTS documents_uploaded_at ON documents (uploaded_at);
CREATE INDEX IF NOT EXISTS attachments_document ON attachments (document_id, kind);
`;
